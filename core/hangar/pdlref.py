"""Generate docs/pdl/reference.md from schema/plane.schema.json (pure, deterministic, LF only)."""
from __future__ import annotations

import json
from pathlib import Path

from .design import SCHEMA_PATH


def _branch_label(b: dict) -> str:
    if "required" in b:
        return ", ".join(f"`{k}`" for k in b["required"])
    return _type_of(b)


def _type_of(n: dict) -> str:
    if "$ref" in n:
        return f"`{n['$ref'].rsplit('/', 1)[-1]}`"
    if "enum" in n:
        return "one of " + ", ".join(f"`{v}`" for v in n["enum"])
    if "const" in n:
        return f"`{n['const']}`"
    if "oneOf" in n:
        return "one of: " + " / ".join(_branch_label(b) for b in n["oneOf"])
    t = n.get("type", "any")
    if t == "array":
        return f"array of {_type_of(n['items'])}" if "items" in n else "array"
    if isinstance(t, list):
        return "/".join(t)
    return t


def _desc(n: dict) -> str:
    return n.get("description", "").replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def _rows(node: dict, prefix: str) -> list[str]:
    out = []
    for name, sub in node["properties"].items():
        req = "yes" if name in node.get("required", []) else ""
        out.append(f"| `{prefix}{name}` | {_type_of(sub)} | {req} | {_desc(sub)} |")
        if "properties" in sub:
            out += _rows(sub, f"{prefix}{name}.")
        elif sub.get("type") == "array" and isinstance(sub.get("items"), dict) and "properties" in sub["items"]:
            out += _rows(sub["items"], f"{prefix}{name}[].")
    return out


def _table(node: dict) -> list[str]:
    return ["| Field | Type | Required | Description |", "|---|---|---|---|", *_rows(node, "")]


def build_reference(schema: dict | None = None) -> str:
    if schema is None:
        schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    lines = [
        f"# {schema['title']} reference",
        "",
        "<!-- GENERATED by schema.docs (plane schema docs) from schema/plane.schema.json. Do not edit by hand. -->",
        "",
        schema["description"],
        "",
        "## Top-level fields",
        "",
        *_table(schema),
        "",
        "## Definitions",
    ]
    for name, d in schema["$defs"].items():
        lines += ["", f"### `{name}`", ""]
        if d.get("description"):
            lines += [d["description"], ""]
        if "properties" in d:
            lines += _table(d)
        elif "oneOf" in d:
            lines += [f"- {_branch_label(b)}" for b in d["oneOf"]]
        else:
            lines.append(f"Type: {_type_of(d)}")
            if "pattern" in d:
                lines += ["", f"Pattern: `{d['pattern']}`"]
        while lines[-1] == "":
            lines.pop()
    return "\n".join(lines) + "\n"


def write_reference(out: Path) -> Path:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(build_reference().encode("utf-8"))
    return out
