"""Generate docs/cli.md from the ops registry (pure, deterministic, LF only)."""
from __future__ import annotations

from pathlib import Path

from .ops import registry

HEADER = "<!-- GENERATED by docs.cli (plane docs cli --out docs/cli.md) from the ops registry. Do not edit by hand. -->"


def _usage(spec) -> str:
    parts = ["plane", spec.group, spec.verb]
    for p in spec.params:
        if p.kind == "argument":
            parts.append(f"[{p.cli_name}...]" if p.type_name == "list[str]" else f"<{p.cli_name}>")
        elif p.type_name == "bool":
            parts.append(f"[--{p.cli_name}]")
        else:
            opt = f"--{p.cli_name} <{p.type_name}>"
            parts.append(opt if p.required else f"[{opt}]")
    return " ".join(parts)


def _param_line(p) -> str:
    flag = f"`<{p.cli_name}>`" if p.kind == "argument" else f"`--{p.cli_name}`"
    kind = p.type_name + (f", one of {', '.join(p.choices)}" if p.choices else "")
    if p.multiple:
        kind += ", repeatable"
    return f"- {flag}: {kind}, {'required' if p.required else 'optional'}"


def _other_commands() -> list[tuple[str, str]]:
    from .cli import cli
    groups = {s.group for s in registry().values()}
    out = []
    for name, cmd in sorted(cli.commands.items()):
        if name not in groups:
            help_text = (cmd.help or "").strip()
            out.append((name, help_text.splitlines()[0] if help_text else ""))
    return out


def build_cli_reference() -> str:
    specs = registry()
    lines = [HEADER, "", "# plane command reference", "",
             f"{len(specs)} operations, generated from `plane ops list`. Every operation also takes `--json` "
             "(prints the OpResult as JSON) and is an MCP tool (see [mcp.md](mcp.md)).", ""]
    group = None
    for name, s in specs.items():
        if s.group != group:
            group = s.group
            lines += [f"## {group}", ""]
        lines += [f"### `plane {s.group} {s.verb}`", "", s.summary.strip(), "", "```", _usage(s), "```", ""]
        if s.mutates:
            lines += ["Writes files.", ""]
        if s.params:
            lines += [_param_line(p) for p in s.params] + [""]
    lines += ["## Other commands", "", "Commands that are not registry operations (old forms and CLI-only commands):", ""]
    lines += [f"- `plane {n}`: {h}" for n, h in _other_commands()]
    return "\n".join(lines) + "\n"


def write_cli_reference(out: Path) -> Path:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(build_cli_reference().encode("utf-8"))
    return out
